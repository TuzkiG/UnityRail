#!/usr/bin/env bun
// Generates the Unity bridge package that ships inside the app bundle. The C# package under
// `unity-package/com.thinkrail.bridge` is the source of truth; this file is a generated copy so a
// packaged binary can install it into a project without a checkout on disk.
//
// Run: bun packages/unity-project/scripts/embed-bridge-package.ts   (or --check to verify freshness)

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";

const here = dirname(import.meta.dir);
const repoRoot = resolve(here, "..", "..");
const packageRoot = join(repoRoot, "unity-package", "com.thinkrail.bridge");
const output = join(here, "src", "bridge", "embeddedPackage.ts");

function walk(dir: string, files: string[] = []): string[] {
	for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
		a.name.localeCompare(b.name),
	)) {
		const path = join(dir, entry.name);
		if (entry.isDirectory()) walk(path, files);
		else if (entry.isFile()) files.push(path);
	}
	return files;
}

const entries = walk(packageRoot).map((path) => ({
	path: relative(packageRoot, path).split(sep).join("/"),
	content: readFileSync(path, "utf8"),
}));

const manifest = JSON.parse(readFileSync(join(packageRoot, "package.json"), "utf8")) as {
	name: string;
	version: string;
};

const generated = `// GENERATED by packages/unity-project/scripts/embed-bridge-package.ts — do not edit.
// Source: unity-package/com.thinkrail.bridge
export const EMBEDDED_BRIDGE_PACKAGE_NAME = ${JSON.stringify(manifest.name)};
export const EMBEDDED_BRIDGE_PACKAGE_VERSION = ${JSON.stringify(manifest.version)};
export const EMBEDDED_BRIDGE_PACKAGE_FILES: Readonly<Record<string, string>> = {
${entries.map((entry) => `\t${JSON.stringify(entry.path)}: ${JSON.stringify(entry.content)},`).join("\n")}
};
`;

if (process.argv.includes("--check")) {
	const current = (() => {
		try {
			return readFileSync(output, "utf8");
		} catch {
			return "";
		}
	})();
	if (current !== generated) {
		console.error(
			"unity-bridge-package: embeddedPackage.ts is STALE — run bun packages/unity-project/scripts/embed-bridge-package.ts",
		);
		process.exit(1);
	}
	console.log(
		`unity-bridge-package: up to date (${entries.length} files, ${manifest.name}@${manifest.version})`,
	);
} else {
	writeFileSync(output, generated);
	console.log(
		`unity-bridge-package: wrote ${entries.length} files from ${manifest.name}@${manifest.version} (${Math.round(statSync(output).size / 1024)} KiB)`,
	);
}
